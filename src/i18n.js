export const LangContext = createContext(null);
export function useLanguageState() {
  const [lang, setLang] = useState(() => {
    try {
      const saved = localStorage.getItem("stb-language");
      if (saved === "zh" || saved === "en") return saved;
      for (const language of navigator.languages || [navigator.language]) {
        if (/^zh\b/i.test(language)) return "zh";
        if (/^en\b/i.test(language)) return "en";
      }
    } catch {
      /* Browser preferences may be unavailable. */
    }
    return "zh";
  });
  const changeLanguage = (value) => {
    setLang(value);
    try {
      localStorage.setItem("stb-language", value);
    } catch {
      /* Keep this tab's preference. */
    }
  };
  const t = (key, values = {}) =>
    Object.entries(values).reduce(
      (s, [name, value]) => s.replaceAll(`{${name}}`, String(value)),
      (lang === "zh" ? zh : en)[key] || zh[key] || key,
    );
  return { lang, setLang: changeLanguage, t };
}
